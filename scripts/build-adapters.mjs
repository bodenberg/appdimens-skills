#!/usr/bin/env node
// Generates the Codex (AGENTS.md) and Cursor (.mdc rules) adapters from skills/ — the single
// source of truth. Run after editing any SKILL.md:  node scripts/build-adapters.mjs
// CI / pre-commit:                                    node scripts/build-adapters.mjs --check
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = join(root, 'skills');
const outDir = join(root, 'adapters');
// Where install.mjs copies the package inside a consumer project (Codex / Cursor).
export const INSTALL_DIR = '.appdimens';

// Cursor globs per skill (auto-attach when a matching file is in context).
const GLOBS = {
  'appdimens-android': '**/*.kt',
  'appdimens-android-xml': '**/res/**/*.xml',
  'appdimens-kmp': '**/commonMain/**/*.kt',
  'appdimens-apple': '**/*.swift',
  'appdimens-flutter': '**/*.dart',
  'appdimens-react-native': '**/*.tsx,**/*.jsx',
  'appdimens-web': '**/*.css,**/*.scss,**/*.html,**/*.vue,**/*.svelte,**/*.astro',
  'appdimens-dotnet': '**/*.xaml,**/*.cs',
};

const ORDER = ['appdimens-layout-intent', 'appdimens-design-to-code', 'appdimens-design-authoring', 'appdimens-code-edit'];

function parseSkill(dir) {
  const raw = readFileSync(join(skillsDir, dir, 'SKILL.md'), 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${dir}/SKILL.md has no frontmatter`);
  const meta = Object.fromEntries(
    m[1].split('\n').map((l) => {
      const i = l.indexOf(':');
      return [l.slice(0, i).trim(), l.slice(i + 1).trim()];
    }),
  );
  if (meta.name !== dir) throw new Error(`${dir}/SKILL.md: name "${meta.name}" must equal the folder name`);
  if (!meta.description) throw new Error(`${dir}/SKILL.md: description is required`);
  return { dir, name: meta.name, description: meta.description, body: m[2].trim() };
}

/** Rewrites package-relative paths so they resolve from a consumer repo root. */
function rewrite(body, skillDir) {
  return body
    .replace(/<(this-)?package>/g, INSTALL_DIR)
    .replace(/\]\((?!https?:|#)(\.\.\/)?([^)]+)\)/g, (_, up, path) =>
      up ? `](${INSTALL_DIR}/skills/${path})` : `](${INSTALL_DIR}/skills/${skillDir}/${path})`,
    )
    .replace(/`\.\.\/appdimens-layout-intent\//g, `\`${INSTALL_DIR}/skills/appdimens-layout-intent/`)
    .replace(/`schemas\//g, `\`${INSTALL_DIR}/schemas/`);
}

const header = (what) =>
  `<!-- Generated by scripts/build-adapters.mjs from skills/ — do not edit by hand. -->\n<!-- ${what} -->\n`;

function build() {
  const dirs = readdirSync(skillsDir).filter((d) => existsSync(join(skillsDir, d, 'SKILL.md')));
  const skills = dirs.map(parseSkill).sort((a, b) => {
    const ia = ORDER.indexOf(a.dir);
    const ib = ORDER.indexOf(b.dir);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.dir.localeCompare(b.dir);
  });
  const files = new Map();

  // Codex: AGENTS.md section. The core skill is inlined; the rest are read on demand.
  const core = skills.find((s) => s.dir === 'appdimens-layout-intent');
  const others = skills.filter((s) => s !== core);
  const agents = [
    header('Paste between the markers into your AGENTS.md, or run: node scripts/install.mjs --target codex <project>'),
    '<!-- appdimens-skills:start -->',
    '## AppDimens — layout intent and responsive sizing',
    '',
    `This project uses AppDimens. The full kit is in \`${INSTALL_DIR}/\`. Before writing, converting, reviewing or editing UI sizes, follow the core workflow below, then **read the matching skill file** from the table and follow it.`,
    '',
    '| When | Read |',
    '|---|---|',
    ...others.map((s) => `| ${s.description.split('. ')[0].replace(/\|/g, '\\|')}. | \`${INSTALL_DIR}/skills/${s.dir}/SKILL.md\` |`),
    '',
    `Validate every change: \`node ${INSTALL_DIR}/tools/appdimens-kit/cli.mjs lint <changed files>\`.`,
    '',
    '### Core workflow (appdimens-layout-intent)',
    '',
    rewrite(core.body, core.dir).replace(/^# .*\n/, '').replace(/^## /gm, '#### '),
    '<!-- appdimens-skills:end -->',
    '',
  ].join('\n');
  files.set(join(outDir, 'codex', 'AGENTS.md'), agents);

  // Cursor: one rule per skill.
  for (const s of skills) {
    const globs = GLOBS[s.dir];
    const fm = ['---', `description: ${s.description}`, `globs: ${globs ?? ''}`, `alwaysApply: false`, '---'].join('\n');
    files.set(join(outDir, 'cursor', 'rules', `${s.dir}.mdc`), `${fm}\n${header(`Source: skills/${s.dir}/SKILL.md`)}\n${rewrite(s.body, s.dir)}\n`);
  }
  return files;
}

const check = process.argv.includes('--check');
const files = build();
let stale = 0;
for (const [path, content] of files) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    stale++;
    console.error(`stale: ${path.replace(root + '/', '')}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path.replace(root + '/', '')}`);
  }
}
if (check && stale) {
  console.error(`${stale} adapter file(s) out of date. Run: node scripts/build-adapters.mjs`);
  process.exit(1);
}
if (check) console.log('adapters are up to date');
