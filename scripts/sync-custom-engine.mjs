#!/usr/bin/env node
// Regenerates tools/appdimens-kit/lib/custom-engine.mjs from the webdimens sources, so the kit
// computes custom strategies with exactly the same engine as every AppDimens platform.
// Usage: node scripts/sync-custom-engine.mjs <path to appdimens-web checkout>   (needs its node_modules)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const web = resolve(process.argv[2] ?? '../appdimens-web');
const dir = mkdtempSync(join(tmpdir(), 'custom-engine-'));
const entry = join(dir, 'entry.ts');
writeFileSync(entry, `export * from ${JSON.stringify(join(web, 'src/custom/engine'))};\nexport * from ${JSON.stringify(join(web, 'src/custom/expression'))};\n`);
const out = join(dir, 'out.mjs');
execFileSync(join(web, 'node_modules/.bin/esbuild'), [entry, '--bundle', '--format=esm', '--platform=neutral', '--target=es2020', `--outfile=${out}`], { stdio: 'inherit' });
const target = new URL('../tools/appdimens-kit/lib/custom-engine.mjs', import.meta.url);
writeFileSync(target, `// GENERATED by scripts/sync-custom-engine.mjs from webdimens src/custom/{engine,expression}.ts.\n// Do not edit: change the webdimens sources and re-run the script.\n// @ts-nocheck\n${readFileSync(out, 'utf8').replace(/^\/\/ .*entry\.ts\n/m, '').replace(/^\/\/ \S*src\/custom\/(\w+\.ts)$/gm, '// webdimens src/custom/$1')}`);
console.log(`wrote ${target.pathname}`);
